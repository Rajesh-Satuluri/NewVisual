#!/usr/bin/env node
/*
 * bake-edits.mjs — turn a cloud-sync state snapshot into the committed
 * `data/user_overrides.js` file that bakes the user's in-tool edits
 * (logic / description / code) into the deployed site.
 *
 * Usage:
 *   node scripts/bake-edits.mjs <input-state.json> <output-overrides.js>
 *
 * The input may be any of:
 *   • the raw Supabase study_get response: [{ "state": {...}, "updated_at": ... }]
 *   • a single { "state": {...} } object
 *   • a raw store export (blind75-progress.json) with logicEdits/descEdits/
 *     codeEdits at the top level
 *
 * Output is a self-contained, ES5-safe script that defines
 * window.BLIND75.USER_OVERRIDES and applies it onto every registered problem.
 * This file is GENERATED — never edit it by hand.
 */
import fs from "node:fs";

function fail(msg) { console.error("bake-edits: " + msg); process.exit(1); }

var inPath = process.argv[2];
var outPath = process.argv[3];
if (!inPath || !outPath) fail("usage: bake-edits.mjs <input.json> <output.js>");

var raw = "";
try { raw = fs.readFileSync(inPath, "utf8"); } catch (e) { fail("cannot read " + inPath + ": " + e.message); }

// An empty cloud row (unknown sync code) comes back as "[]" or "" — treat as
// "no edits" and still emit a valid (empty) overrides file.
var parsed = null;
if (raw.trim()) {
  try { parsed = JSON.parse(raw); } catch (e) { fail("input is not valid JSON: " + e.message); }
}

// Dig out the state bundle regardless of which wrapper shape we got.
function extractState(p) {
  if (p == null) return {};
  if (Array.isArray(p)) return p.length ? extractState(p[0]) : {};
  if (p.state && typeof p.state === "object") return p.state;      // {state:{...}}
  return p;                                                         // raw export
}
var state = extractState(parsed) || {};

var logic = state.logicEdits || {};  // id -> { "<ai>": markdown }
var desc  = state.descEdits  || {};  // id -> markdown
var code  = state.codeEdits  || {};  // id -> { "<ai>:<mode>": source }

// --- shape / count report (shows up in the Actions log) ---
function countNested(o) { var n = 0, k, kk; for (k in o) for (kk in o[k]) n++; return n; }
function countFlat(o) { var n = 0, k; for (k in o) n++; return n; }
var nLogic = countNested(logic), nDesc = countFlat(desc), nCode = countNested(code);
console.log("bake-edits: logic=" + nLogic + " desc=" + nDesc + " code=" + nCode);

var payload = { logic: logic, desc: desc, code: code };
var json = JSON.stringify(payload, null, 2);
var stamp = new Date().toISOString();

var out =
'/* user_overrides.js — GENERATED by scripts/bake-edits.mjs. DO NOT EDIT BY HAND.\n' +
'   Baked from cloud sync by .github/workflows/bake-edits.yml. It overlays the\n' +
'   user\'s in-tool edits (logic / description / code) onto the problems at load,\n' +
'   so edits render for everyone and are captured in the Backup (.zip).\n' +
'   generatedAt: ' + stamp + '\n' +
'   edits: logic=' + nLogic + ' desc=' + nDesc + ' code=' + nCode + ' */\n' +
'(function () {\n' +
'  "use strict";\n' +
'  var B = window.BLIND75 || (window.BLIND75 = {});\n' +
'\n' +
'  var OV = ' + json + ';\n' +
'  OV.generatedAt = "' + stamp + '";\n' +
'  B.USER_OVERRIDES = OV;\n' +
'\n' +
'  // Every problem registry the unified app exposes an .all() on.\n' +
'  function registries() {\n' +
'    return [B, window.PYDSA, window.PYSPARK, window.SQLLAB,\n' +
'            window.NUMPY, window.PANDAS, window.LEARN];\n' +
'  }\n' +
'\n' +
'  function applyToProblem(p) {\n' +
'    if (!p || !p.id) return;\n' +
'    var id = p.id;\n' +
'    if (OV.desc[id] != null && typeof p.description === "string") {\n' +
'      p.description = OV.desc[id];\n' +
'    }\n' +
'    var lg = OV.logic[id];\n' +
'    if (lg && p.approaches) {\n' +
'      for (var k in lg) if (lg.hasOwnProperty(k)) {\n' +
'        var ai = parseInt(k, 10);\n' +
'        if (p.approaches[ai]) p.approaches[ai].logic = lg[k];\n' +
'      }\n' +
'    }\n' +
'    var cd = OV.code[id];\n' +
'    if (cd && p.approaches) {\n' +
'      for (var kk in cd) if (cd.hasOwnProperty(kk)) {\n' +
'        var parts = kk.split(":");\n' +
'        var ci = parseInt(parts[0], 10);\n' +
'        var mode = parts[1];\n' +
'        if (p.approaches[ci] && (mode === "rcs" || mode === "plain")) {\n' +
'          p.approaches[ci][mode] = cd[kk];\n' +
'        }\n' +
'      }\n' +
'    }\n' +
'  }\n' +
'\n' +
'  function applyAll() {\n' +
'    var regs = registries(), i, j;\n' +
'    for (i = 0; i < regs.length; i++) {\n' +
'      var r = regs[i];\n' +
'      if (!r || typeof r.all !== "function") continue;\n' +
'      var list;\n' +
'      try { list = r.all(); } catch (e) { continue; }\n' +
'      if (!list || !list.length) continue;\n' +
'      for (j = 0; j < list.length; j++) applyToProblem(list[j]);\n' +
'    }\n' +
'  }\n' +
'  B.applyOverridesAll = applyAll;\n' +
'\n' +
'  applyAll();\n' +
'  // Re-apply after a cloud pull brings newer data, and after lazy stacks load.\n' +
'  window.addEventListener("blind75:cloud-refresh", applyAll);\n' +
'})();\n';

try { fs.writeFileSync(outPath, out); } catch (e) { fail("cannot write " + outPath + ": " + e.message); }
console.log("bake-edits: wrote " + outPath + " (" + out.length + " bytes)");
