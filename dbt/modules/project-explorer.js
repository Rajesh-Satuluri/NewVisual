// Sample Project Explorer (Iter 5)
// Browse a complete, runnable dbt project (jaffle_commerce) as a source-file
// tree, read each file with highlighting, and download the whole thing as a
// self-extracting shell script you can actually `dbt run`. Nothing is executed
// in the browser — this module only displays and packages real dbt source.
import { createModuleShell, createIQSection, injectCodeEnhancements } from '../components/module-shell.js';
import { FILES, TREE_ORDER, PROJECT_NAME, fileCount } from '../data/sample-project.js';

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Build a nested tree { name, path, children:[], file? } from flat FILES paths.
function buildTree() {
  const root = { name: PROJECT_NAME, path: '', children: [], dir: true };
  const dirMap = new Map([['', root]]);
  const paths = Object.keys(FILES);

  // Deterministic order: TREE_ORDER prefix rank, then alpha.
  const rank = p => {
    for (let i = 0; i < TREE_ORDER.length; i++) {
      const t = TREE_ORDER[i];
      if (t.endsWith('/') ? p.startsWith(t) : p === t) return i;
    }
    return TREE_ORDER.length;
  };
  paths.sort((a, b) => (rank(a) - rank(b)) || a.localeCompare(b));

  for (const path of paths) {
    const parts = path.split('/');
    let cur = '';
    let parent = root;
    for (let i = 0; i < parts.length; i++) {
      const isLeaf = i === parts.length - 1;
      cur = cur ? `${cur}/${parts[i]}` : parts[i];
      if (isLeaf) {
        parent.children.push({ name: parts[i], path, dir: false });
      } else {
        let node = dirMap.get(cur);
        if (!node) {
          node = { name: parts[i], path: cur, children: [], dir: true };
          dirMap.set(cur, node);
          parent.children.push(node);
        }
        parent = node;
      }
    }
  }
  return root;
}

const FILE_ICON = { yaml: '⚙️', yml: '⚙️', sql: '🔹', md: '📄', csv: '📊', text: '📃' };
function iconFor(node) {
  if (node.dir) return '📁';
  return FILE_ICON[FILES[node.path]?.lang] || '📃';
}

function renderTree(node, depth = 0) {
  if (node.dir && depth > 0) {
    return `
      <div class="pe-dir" style="--d:${depth}">
        <div class="pe-row pe-dirrow"><span class="pe-ico">📁</span>${esc(node.name)}/</div>
        ${node.children.map(c => renderTree(c, depth + 1)).join('')}
      </div>`;
  }
  if (node.dir) {
    // root: render children only
    return node.children.map(c => renderTree(c, depth + 1)).join('');
  }
  return `<div class="pe-row pe-file" data-path="${esc(node.path)}" role="button" tabindex="0" style="--d:${depth}">
    <span class="pe-ico">${iconFor(node)}</span>${esc(node.name)}</div>`;
}

// Self-extracting POSIX script: writes every file via quoted heredocs, so it
// recreates the project byte-for-byte, then prints run instructions.
function buildSetupScript() {
  let out = `#!/usr/bin/env bash
# jaffle_commerce — self-extracting dbt sample project.
# Generated by the dbt mastery platform's Sample Project Explorer.
# Usage:  bash setup_${PROJECT_NAME}.sh && cd ${PROJECT_NAME} && dbt seed && dbt build
set -euo pipefail
ROOT="${PROJECT_NAME}"
mkdir -p "$ROOT"
cd "$ROOT"
`;
  for (const [path, { body }] of Object.entries(FILES)) {
    const dir = path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '';
    if (dir) out += `mkdir -p ${JSON.stringify(dir)}\n`;
    // Quoted heredoc delimiter => no shell expansion of $ or backticks in body.
    out += `cat > ${JSON.stringify(path)} <<'JAFFLE_EOF'\n${body}\nJAFFLE_EOF\n`;
  }
  out += `
echo ""
echo "✓ ${PROJECT_NAME} written (${fileCount} files)."
echo "Next:"
echo "  cd ${PROJECT_NAME}"
echo "  pip install dbt-duckdb"
echo "  dbt seed && dbt build"
`;
  return out;
}

function download(filename, text, type = 'text/plain') {
  const blob = new Blob([text], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

