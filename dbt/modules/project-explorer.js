export function mount(container) {
  const tree = buildTree();

  container.innerHTML = createModuleShell({
    tag: 'Practice · Sample Project',
    title: 'Sample Project Explorer',
    subtitle: `Browse a complete, runnable dbt project — ${fileCount} real source files — then download it and <code>dbt run</code> it locally on DuckDB. Nothing here is executed in the browser; the Explorer only displays and packages the files.`,
    tabs: [
      { id: 'explore', label: '📂 Explore' },
      { id: 'run', label: '▶️ Run it locally' },
      { id: 'iq', label: '🎯 Interview Q&A' },
    ],
  });

  // ── Explore tab ──────────────────────────────────────────────────────────
  const firstPath = 'dbt_project.yml';
  container.querySelector('#tab-explore').innerHTML = `
    <div class="pe-layout">
      <aside class="pe-tree" aria-label="Project files">
        <div class="pe-treehead">📦 ${PROJECT_NAME}/</div>
        ${renderTree(tree)}
      </aside>
      <section class="pe-viewer">
        <div class="pe-filehead"><span id="pe-filename"></span>
          <button class="pe-dl1" id="pe-dl-file" type="button">⬇ this file</button></div>
        <div class="code-block" id="pe-filebody" data-lang="sql"></div>
      </section>
    </div>`;

  const viewer = container.querySelector('#tab-explore');
  const nameEl = viewer.querySelector('#pe-filename');
  let activePath = null;

  function showWrap(path) {
    const current = viewer.querySelector('#pe-filebody');
    const f = FILES[path];
    if (!f || !current) return;
    activePath = path;
    nameEl.textContent = path;
    const fresh = document.createElement('div');
    fresh.className = 'code-block';
    fresh.id = 'pe-filebody';
    fresh.dataset.lang = f.lang;
    fresh.textContent = f.body;
    current.replaceWith(fresh);
    injectCodeEnhancements(viewer);
    viewer.querySelectorAll('.pe-row.pe-file').forEach(r =>
      r.classList.toggle('active', r.dataset.path === path));
  }

  viewer.querySelectorAll('.pe-row.pe-file').forEach(row => {
    const go = () => showWrap(row.dataset.path);
    row.addEventListener('click', go);
    row.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); go(); } });
  });
  viewer.querySelector('#pe-dl-file').addEventListener('click', () => {
    if (!activePath) return;
    download(activePath.split('/').pop(), FILES[activePath].body);
  });
  showWrap(firstPath);

  // ── Run tab ──────────────────────────────────────────────────────────────
  container.querySelector('#tab-run').innerHTML = `
    <div class="pe-run">
      <p class="pe-lead">Download the project as a <strong>self-extracting script</strong> — it recreates all ${fileCount} files, then runs on DuckDB with no warehouse and no cloud account. This is a <strong>real, runnable dbt project</strong>, not a simulation.</p>
      <button class="pe-dl-main" id="pe-dl-all" type="button">⬇ Download setup_${PROJECT_NAME}.sh</button>
      <div class="pe-steps">
        <div class="pe-step"><span class="pe-stepn">1</span><div><strong>Extract</strong><div class="code-block" data-lang="bash">bash setup_${PROJECT_NAME}.sh
cd ${PROJECT_NAME}</div></div></div>
        <div class="pe-step"><span class="pe-stepn">2</span><div><strong>Install the adapter</strong> (pulls in dbt-core)<div class="code-block" data-lang="bash">pip install dbt-duckdb</div></div></div>
        <div class="pe-step"><span class="pe-stepn">3</span><div><strong>Seed + build</strong> — loads CSVs, runs models, runs tests, in DAG order<div class="code-block" data-lang="bash">dbt seed
dbt build</div></div></div>
        <div class="pe-step"><span class="pe-stepn">4</span><div><strong>Explore the output</strong><div class="code-block" data-lang="bash">dbt docs generate && dbt docs serve
duckdb jaffle.duckdb "select * from analytics_marts.fct_orders"</div></div></div>
      </div>
      <p class="pe-note">💡 The script uses quoted heredocs, so file contents are written verbatim — no shell expansion. Read it before running; it only writes files under <code>./${PROJECT_NAME}/</code> and prints next steps.</p>
    </div>`;
  container.querySelector('#pe-dl-all').addEventListener('click', () => {
    download(`setup_${PROJECT_NAME}.sh`, buildSetupScript(), 'text/x-shellscript');
  });

  // ── IQ tab ───────────────────────────────────────────────────────────────
  container.querySelector('#tab-iq').innerHTML = createIQSection(IQ);

  injectCodeEnhancements(container);
}
